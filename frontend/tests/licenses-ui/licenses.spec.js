import { expect, test } from '@playwright/test'

for (const width of [320, 375, 768, 1280]) test(`license overlay wraps text and scrolls vertically at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 640 })
  await page.route('**/api/**', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"preview only"}' }))
  await page.goto('/login')
  const trigger = page.getByRole('button', { name: 'オープンソースライセンス', exact: true })
  expect(await trigger.evaluate(element => ({ inCard: Boolean(element.closest('.login-card')), background: getComputedStyle(element).backgroundColor, shadow: getComputedStyle(element).boxShadow }))).toEqual({ inCard: false, background: 'rgba(0, 0, 0, 0)', shadow: 'none' })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await dialog.locator('summary').first().click()
  const content = dialog.locator('.license-content')
  const before = await content.evaluate(element => ({ width: element.clientWidth, scrollWidth: element.scrollWidth, height: element.clientHeight, scrollHeight: element.scrollHeight }))
  expect(before.scrollWidth).toBe(before.width)
  expect(before.scrollHeight).toBeGreaterThan(before.height)
  const close = dialog.getByRole('button', { name: 'ライセンスを閉じる', exact: true })
  const closeBefore = await close.boundingBox()
  await content.evaluate(element => { element.scrollTop = element.scrollHeight })
  expect(await content.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  await expect(close).toBeInViewport()
  expect((await close.boundingBox()).y).toBe(closeBefore.y)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await close.click()
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
})
